/**
 * Main Translation Function
 * @param {string} keyOrText - Key or English text string
 * @param {string} lang - 'en' or 'hi'
 * @returns {string} Translated string
 */
export const translate = (keyOrText, lang = 'en') => {
  if (!keyOrText) return '';
  if (typeof keyOrText !== 'string') return String(keyOrText);

  if (lang === 'en') {
    return translations.en[keyOrText] || keyOrText;
  }

  // 1. Direct key lookup in translations.hi
  if (translations.hi[keyOrText]) {
    return translations.hi[keyOrText];
  }

  // 2. Direct phrase lookup in phraseDictionary
  if (phraseDictionary[keyOrText]) {
    return phraseDictionary[keyOrText];
  }

  // 3. Trimmed phrase lookup
  const trimmed = keyOrText.trim();
  if (phraseDictionary[trimmed]) {
    return phraseDictionary[trimmed];
  }

  // 4. Case-insensitive phrase lookup
  const lower = trimmed.toLowerCase();
  for (const [k, v] of Object.entries(phraseDictionary)) {
    if (k.toLowerCase() === lower) {
      return v;
    }
  }

  // 5. Smart unit & pattern replacement in Hindi
  let str = trimmed;
  if (/^\d+(\.\d+)?\s*(Posts|posts)$/i.test(str)) {
    return str.replace(/\s*(Posts|posts)/i, ' चौकियां');
  }
  if (/^\d+(\.\d+)?\s*(Days|days|d)(\s*left)?$/i.test(str)) {
    return str.replace(/\s*(Days|days|d)(\s*left)?/i, ' दिन शेष');
  }
  if (/^\d+(\.\d+)?\s*(units|Units|u)$/i.test(str)) {
    return str.replace(/\s*(units|Units|u)/i, ' इकाइयां');
  }
  if (/^\d+(\.\d+)?\s*(liters|L)$/i.test(str)) {
    return str.replace(/\s*(liters|L)/i, ' लीटर');
  }
  if (/^\d+(\.\d+)?\s*kg$/i.test(str)) {
    return str.replace(/\s*kg$/i, ' किग्रा');
  }
  if (/^Loading\s+(.+)\s+Dashboard\.\.\.$/i.test(str)) {
    const match = str.match(/^Loading\s+(.+)\s+Dashboard\.\.\.$/i);
    const rolePart = translate(match[1], 'hi');
    return `${rolePart} डैशबोर्ड लोड हो रहा है...`;
  }
  if (/^Error:\s*(.+)$/i.test(str)) {
    return str.replace(/^Error:\s*/i, 'त्रुटि: ');
  }

  // Fallback to English translation or original string
  return translations.en[keyOrText] || keyOrText;
};
